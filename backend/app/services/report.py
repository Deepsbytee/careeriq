"""PDF report for a resume analysis (reportlab). Cherry and matcha, matching the app."""
from __future__ import annotations

import io
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import Flowable, KeepTogether, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

CHERRY = colors.HexColor("#5C0F26")
CHERRY_BRIGHT = colors.HexColor("#C2294A")
MATCHA = colors.HexColor("#5E8A3A")
MATCHA_MIST = colors.HexColor("#EEF2DF")
OCHRE = colors.HexColor("#B7791F")
INK = colors.HexColor("#2A1A1E")
MUTED = colors.HexColor("#6B5E60")
LINE = colors.HexColor("#D3DBB8")
BLOSSOM = colors.HexColor("#F7D9DF")

CATEGORY_LABELS = {
    "structure": "Structure", "completeness": "Completeness", "impact": "Impact",
    "keywords": "Keywords and skills", "readability": "Readability",
}


def _t(value) -> str:
    """Text that the built-in PDF fonts can draw, safely escaped for Paragraph markup."""
    s = "" if value is None else str(value)
    s = s.encode("cp1252", "replace").decode("cp1252")
    return escape(s)


def _score_color(score: float):
    return MATCHA if score >= 70 else OCHRE if score >= 40 else CHERRY_BRIGHT


class _Bars(Flowable):
    def __init__(self, rows: list[tuple[str, float]], width: float):
        super().__init__()
        self.rows, self.width, self.row_h = rows, width, 9 * mm
        self.height = self.row_h * len(rows)

    def wrap(self, *_):
        return self.width, self.height

    def draw(self):
        c, label_w, val_w = self.canv, 42 * mm, 12 * mm
        bar_w = self.width - label_w - val_w
        for i, (label, score) in enumerate(self.rows):
            y = self.height - (i + 1) * self.row_h + 2 * mm
            c.setFillColor(INK)
            c.setFont("Helvetica", 9.5)
            c.drawString(0, y, label)
            c.setFillColor(MATCHA_MIST)
            c.roundRect(label_w, y - 0.5 * mm, bar_w, 3.2 * mm, 1.6 * mm, stroke=0, fill=1)
            c.setFillColor(_score_color(score))
            c.roundRect(label_w, y - 0.5 * mm, max(bar_w * score / 100, 2 * mm), 3.2 * mm, 1.6 * mm, stroke=0, fill=1)
            c.setFillColor(INK)
            c.setFont("Helvetica-Bold", 9.5)
            c.drawRightString(self.width, y, f"{round(score)}")


def _styles() -> dict[str, ParagraphStyle]:
    base = ParagraphStyle("base", fontName="Helvetica", fontSize=9.5, leading=13.5, textColor=INK, alignment=TA_LEFT)
    return {
        "base": base,
        "h2": ParagraphStyle("h2", parent=base, fontName="Times-Bold", fontSize=14, leading=18, textColor=CHERRY, spaceBefore=14, spaceAfter=5),
        "muted": ParagraphStyle("muted", parent=base, textColor=MUTED, fontSize=8.5, leading=12),
        "quote": ParagraphStyle("quote", parent=base, fontName="Helvetica-Oblique", textColor=MUTED, fontSize=8.5, leftIndent=10, spaceAfter=3),
        "item": ParagraphStyle("item", parent=base, leftIndent=10, spaceAfter=3),
        "small": ParagraphStyle("small", parent=base, fontSize=8, leading=11, textColor=MUTED),
    }


def _chrome(candidate: str, filename: str, created: datetime):
    def draw(canvas, doc):
        w, h = A4
        canvas.saveState()
        if doc.page == 1:
            canvas.setFillColor(CHERRY)
            canvas.rect(0, h - 30 * mm, w, 30 * mm, stroke=0, fill=1)
            canvas.setFillColor(colors.HexColor("#F7EDE9"))
            canvas.setFont("Times-Bold", 20)
            canvas.drawString(18 * mm, h - 15 * mm, "CareerIQ resume report")
            canvas.setFont("Helvetica", 9.5)
            canvas.setFillColor(BLOSSOM)
            canvas.drawString(18 * mm, h - 22 * mm, f"{_clean(candidate)}  |  {_clean(filename)}  |  {created:%d %b %Y}")
        canvas.setFillColor(MUTED)
        canvas.setFont("Helvetica", 7.5)
        canvas.drawString(18 * mm, 10 * mm, "Generated by CareerIQ. Scores blend rule-based measurements with AI review.")
        canvas.drawRightString(w - 18 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    return draw


def _clean(s: str) -> str:
    return (s or "").encode("cp1252", "replace").decode("cp1252")


def build_report_pdf(*, candidate: str, filename: str, analysis: dict, rewrites: list[dict] | None, created: datetime) -> bytes:
    st = _styles()
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=18 * mm, bottomMargin=18 * mm,
                            title="CareerIQ resume report", author="CareerIQ")
    width = A4[0] - 36 * mm
    story: list = [Spacer(1, 22 * mm)]

    # ── Score header
    score = float(analysis.get("ats_score") or 0)
    label = "Strong" if score >= 75 else "Solid foundation" if score >= 55 else "Needs work"
    score_style = ParagraphStyle("score", parent=st["base"], leading=54)
    big = Paragraph(f'<font name="Times-Bold" size="46" color="{_score_color(score).hexval().replace("0x", "#")}">{score:.0f}</font>'
                    f'<font size="14" color="#6B5E60"> / 100</font>', score_style)
    summary = Paragraph(f'<b>{_t(label)}</b><br/>{_t(analysis.get("summary") or "")}', st["base"])
    head = Table([[big, summary]], colWidths=[48 * mm, width - 48 * mm])
    head.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "MIDDLE"), ("BACKGROUND", (0, 0), (-1, -1), MATCHA_MIST),
                              ("BOX", (0, 0), (-1, -1), 0.5, LINE), ("LEFTPADDING", (0, 0), (-1, -1), 10),
                              ("TOPPADDING", (0, 0), (-1, -1), 10), ("BOTTOMPADDING", (0, 0), (-1, -1), 10)]))
    story += [head]

    # ── Category bars
    cats = (analysis.get("score_breakdown") or {}).get("categories") or {}
    if cats:
        story.append(Paragraph("Score breakdown", st["h2"]))
        story.append(_Bars([(CATEGORY_LABELS.get(k, k.title()), v.get("score", 0)) for k, v in cats.items()], width))

    # ── Strengths / weaknesses with evidence
    ev = analysis.get("evidence") or {}

    def points(title: str, key: str, fallback: list[str]):
        items = ev.get(key) or [{"point": p, "evidence": None, "verified": None} for p in (fallback or [])]
        if not items:
            return
        story.append(Paragraph(title, st["h2"]))
        for it in items:
            block = [Paragraph(f'&bull;&nbsp; {_t(it.get("point"))}', st["item"])]
            if it.get("evidence"):
                block.append(Paragraph(f'From your resume: &ldquo;{_t(it["evidence"])}&rdquo;', st["quote"]))
            story.append(KeepTogether(block))

    points("What's working", "strengths", analysis.get("strengths"))
    points("What to improve", "weaknesses", analysis.get("weaknesses"))

    recs = analysis.get("recommendations") or []
    if recs:
        story.append(Paragraph("Recommended fixes, most important first", st["h2"]))
        for i, r in enumerate(recs, 1):
            story.append(Paragraph(f"<b>{i}.</b>&nbsp; {_t(r)}", st["item"]))

    if rewrites:
        story.append(Paragraph("Stronger versions of your weakest bullets", st["h2"]))
        story.append(Paragraph("Replace anything in [brackets] with your real figure. Don't publish a number you can't back up.", st["muted"]))
        story.append(Spacer(1, 3))
        for r in rewrites:
            block = Table([[Paragraph("Before", st["small"]), Paragraph(_t(r["original"]), st["base"])],
                           [Paragraph("After", st["small"]), Paragraph(f'<b>{_t(r["rewritten"])}</b>', st["base"])]],
                          colWidths=[14 * mm, width - 14 * mm])
            block.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("BACKGROUND", (0, 1), (-1, 1), MATCHA_MIST),
                                       ("LINEBELOW", (0, 1), (-1, 1), 0.5, LINE), ("TOPPADDING", (0, 0), (-1, -1), 4),
                                       ("BOTTOMPADDING", (0, 0), (-1, -1), 4)]))
            story.append(KeepTogether([block, Spacer(1, 5)]))

    findings = (analysis.get("score_breakdown") or {}).get("findings") or []
    if findings:
        story.append(Paragraph("Measured checks", st["h2"]))
        for f in findings:
            story.append(Paragraph(f"&bull;&nbsp; {_t(f)}", st["item"]))

    skills = analysis.get("skills") or []
    if skills:
        story.append(Paragraph("Skills detected", st["h2"]))
        story.append(Paragraph(_t(", ".join(skills)), st["base"]))

    story.append(Spacer(1, 10))
    story.append(Paragraph(
        "How the score works: structure and completeness are measured by rules. Impact, keywords and readability are "
        "half rule-based measurement, half AI rating. Every quote shown was checked against your resume text.", st["small"]))

    draw = _chrome(candidate, filename, created)
    doc.build(story, onFirstPage=draw, onLaterPages=draw)
    return buf.getvalue()
